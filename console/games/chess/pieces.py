def _mask(rows: list[str]) -> list[list[bool]]:
    return [[ch == "#" for ch in row] for row in rows]


def silhouette(piece: int) -> list[list[bool]]:
    return _mask(_ART[abs(piece)])


def outline(mask: list[list[bool]]) -> list[list[bool]]:
    """Pixels touching the silhouette (8-neighbourhood) that are not part of it."""
    n = len(mask)
    out = [[False] * n for _ in range(n)]
    for y in range(n):
        for x in range(n):
            if mask[y][x]:
                continue
            for dy in (-1, 0, 1):
                for dx in (-1, 0, 1):
                    yy, xx = y + dy, x + dx
                    if 0 <= yy < n and 0 <= xx < n and mask[yy][xx]:
                        out[y][x] = True
    return out
